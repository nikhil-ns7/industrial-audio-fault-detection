_BEATS_MODEL = None


def _load_beats():
    global _BEATS_MODEL
    if _BEATS_MODEL is not None:
        return _BEATS_MODEL

    print("Loading BEATs checkpoint...")
    checkpoint = torch.load(BEATS_CHECKPOINT, map_location="cpu")
    cfg = BEATsConfig(checkpoint["cfg"])
    model = BEATs(cfg)
    model.load_state_dict(checkpoint["model"])
    model.eval()
    _BEATS_MODEL = model
    print("BEATs loaded successfully.")
    return _BEATS_MODEL


def _load_audio(audio_path):
    waveform, sample_rate = torchaudio.load(audio_path)
    if waveform.shape[0] > 1:
        waveform = waveform.mean(dim=0, keepdim=True)
    if sample_rate != 16000:
        resampler = torchaudio.transforms.Resample(
            orig_freq=sample_rate, new_freq=16000
        )
        waveform = resampler(waveform)
    return waveform.float()


def _predict_from_embedding(embedding):
    embedding = np.asarray(embedding, dtype=np.float32).reshape(-1)
    if embedding.shape[0] != 768:
        raise ValueError(
            "Expected a 768-dimensional BEATs embedding, got "
            + str(embedding.shape[0])
        )

    score = float(np.dot(CLASSIFIER_WEIGHTS, embedding) + CLASSIFIER_INTERCEPT)

    if score >= 0:
        p1 = 1.0 / (1.0 + np.exp(-score))
    else:
        exp_score = np.exp(score)
        p1 = exp_score / (1.0 + exp_score)

    p0 = 1.0 - p1

    if p1 >= 0.5:
        prediction = "Abnormal"
        confidence = p1 * 100.0
    else:
        prediction = "Normal"
        confidence = p0 * 100.0

    return {
        "prediction": prediction,
        "confidence": confidence,
        "normal_probability": p0 * 100.0,
        "abnormal_probability": p1 * 100.0,
    }


def predict_beats(audio_path):
    model = _load_beats()
    audio = _load_audio(audio_path)

    with torch.no_grad():
        representation = model.extract_features(
            audio, padding_mask=None
        )[0]
        embedding = representation.mean(dim=1).cpu().numpy()[0]

    return _predict_from_embedding(embedding)
